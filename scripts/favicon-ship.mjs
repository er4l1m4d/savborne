// Savborne app icons — favicon, icon, apple-icon.
//
// The mark is the handoff document's own logo (Savborne-handoff.html, the svg with
// aria-label="Savborne icon"): a 24x24 rounded square in #0C3B35, a cream #F6EFD9 pixel
// glyph, and two #FF6A4D coral pixels. Those three colours are declared by
// assets/manifest.json's productPalette, and this is the first place they ship.
//
// The glyph is drawn from a code pixel map rather than hand-typed path data, for the reason
// the A_Gate phone icon taught us: a hand-written map can contain single pixels with no
// 4-neighbour, which only art-gates can see, and only if the markup is in the run dialect it
// parses. Here the map is authoritative and the orphan test runs over it before anything is
// rasterised, so the defect is impossible rather than merely checked for.
//
// What exists today, and why all four files are needed:
//   src/app/favicon.ico    the create-next-app default: 3 BMP entries, black + greys, no brand
//   src/app/icon.svg       new — the mark, vector, used by every modern browser
//   src/app/icon.png       512px — Android home screen and search results
//   src/app/apple-icon.png 180px — iOS requires png/jpg for this convention, so it cannot be the svg
//
// The 24-grid is the only grid this mark has. 48, 96, 128, 256 and 512 are exact multiples;
// 16, 32, 180 and 192 are not, and at 16 a cell is 0.67px. --preview rasterises the real
// pixels and blows them up nearest-neighbour so that cost is visible instead of argued about.
//
//   node scripts/favicon-ship.mjs --preview   writes assets-raw/favicon-preview.html
//   node scripts/favicon-ship.mjs --ship      writes the four icon files
import fs from 'node:fs';
import zlib from 'node:zlib';

const MODE = process.argv.includes('--ship') ? 'ship' : 'preview';
const PREVIEW = 'assets-raw/favicon-preview.html';

const TILE = '#0C3B35';
const GLYPH = '#F6EFD9';
const ACCENT = '#FF6A4D';
const RADIUS = 5.4; // in 24-grid units, exactly as the handoff has it
const GRID = 24;

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));

// ------------------------------------------------------------------ the mark, as a pixel map
// Rows y0..y17 of the handoff's two paths, transcribed to a grid. Every painted cell is run
// through the same 4-neighbour test art-gates applies; a lone pixel is a hard error.
function buildGrid() {
  const g = Array.from({ length: GRID }, () => Array(GRID).fill(null));
  const runs = {
    [GLYPH]: [
      [7, 6, 1], [11, 6, 2], [16, 6, 1],
      [7, 7, 2], [10, 7, 4], [15, 7, 2],
      [7, 8, 2], [10, 8, 4], [15, 8, 2],
      [7, 9, 10],
      [9, 11, 6],
      [8, 12, 2], [14, 12, 2],
      [8, 13, 2],
      [9, 14, 6],
      [14, 15, 2],
      [8, 16, 2], [14, 16, 2],
      [9, 17, 6],
    ],
    [ACCENT]: [[9, 8, 1], [14, 8, 1]],
  };
  for (const [colour, list] of Object.entries(runs)) {
    for (const [x, y, w] of list) for (let i = 0; i < w; i++) g[y][x + i] = colour;
  }
  return g;
}

const grid = buildGrid();

(() => {
  const painted = [];
  for (let y = 0; y < GRID; y++) for (let x = 0; x < GRID; x++) if (grid[y][x]) painted.push([x, y]);
  const orphans = painted.filter(([x, y]) =>
    ![[x - 1, y], [x + 1, y], [x, y - 1], [x, y + 1]].some(([nx, ny]) => grid[ny] && grid[ny][nx]));
  if (orphans.length) throw new Error(`mark has orphan pixels: ${orphans.map((o) => o.join(',')).join(' ')}`);
  // 60 glyph cells (the handoff's 19 runs sum to 60) plus the 2 coral pixels.
  const glyphCells = painted.filter(([x, y]) => grid[y][x] === GLYPH).length;
  const accentCells = painted.filter(([x, y]) => grid[y][x] === ACCENT).length;
  if (glyphCells !== 60) throw new Error(`expected 60 glyph cells, got ${glyphCells}`);
  if (accentCells !== 2) throw new Error(`expected 2 coral cells, got ${accentCells}`);
})();

// The handoff's glyph path, re-emitted from the map. Used by the preview so the vector there
// is generated by the same source the rasters come from, not copied.
const glyphPath = (colour) => {
  let d = '';
  for (let y = 0; y < GRID; y++) {
    let x = 0;
    while (x < GRID) {
      if (grid[y][x] !== colour) { x++; continue; }
      const sx = x;
      while (x < GRID && grid[y][x] === colour) x++;
      d += `M${sx} ${y}h${x - sx}v1h-${x - sx}z`;
    }
  }
  return d;
};

const MARK_SVG = `<svg xmlns="http://www.w3.org/2000/svg" width="${GRID}" height="${GRID}" viewBox="0 0 ${GRID} ${GRID}">`
  + `<rect width="${GRID}" height="${GRID}" rx="${RADIUS}" fill="${TILE}"/>`
  + `<path fill="${GLYPH}" d="${glyphPath(GLYPH)}"/>`
  + `<path fill="${ACCENT}" d="${glyphPath(ACCENT)}"/>`
  + '</svg>';

// The same artwork at an explicit display size, for embedding — built from the same parts so
// there is one geometry, not a copy of it (and no duplicated width/height attributes).
const markAt = (size) => `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${GRID} ${GRID}">`
  + `<rect width="${GRID}" height="${GRID}" rx="${RADIUS}" fill="${TILE}"/>`
  + `<path fill="${GLYPH}" d="${glyphPath(GLYPH)}"/>`
  + `<path fill="${ACCENT}" d="${glyphPath(ACCENT)}"/>`
  + '</svg>';

// ------------------------------------------------------------------ PNG writer
function crc32(buf) {
  let c = ~0;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return ~c >>> 0;
}
const chunk = (type, data) => {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
};
function encodePng(size, rgba) {
  const raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) rgba.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0)),
  ]);
}

// ------------------------------------------------------------------ rasteriser
// Glyph cells are point-sampled, so every glyph pixel is one of the three palette colours
// exactly — no blend, at any size. The tile's edge is the one place that needs coverage:
// hard-thresholding it produced stairs 21px wide at 512. So the rounded rect is sampled by
// signed distance and blended against transparency, which makes the corner curve smoothly at
// every size and keeps the glyph untouched (it never comes within 6 grid units of the edge).
function rasterise(size) {
  const buf = Buffer.alloc(size * size * 4);
  const k = GRID / size;            // grid units per pixel
  const half = GRID / 2;
  const inner = half - RADIUS;      // straight-edge half extent
  const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));
  // signed distance to the rounded square, negative inside, in grid units
  const sdf = (x, y) => {
    const qx = Math.abs(x - half) - inner;
    const qy = Math.abs(y - half) - inner;
    const outside = Math.hypot(Math.max(qx, 0), Math.max(qy, 0));
    const inside = Math.min(Math.max(qx, qy), 0);
    return outside + inside - RADIUS;
  };
  const [tr, tg, tb] = rgb(TILE);
  for (let py = 0; py < size; py++) {
    for (let px = 0; px < size; px++) {
      const gx = (px + 0.5) * k;
      const gy = (py + 0.5) * k;
      const i = (py * size + px) * 4;
      const cell = grid[Math.floor(gy)]?.[Math.floor(gx)] ?? null;
      if (cell) {
        const [r, g, b] = rgb(cell);
        buf[i] = r; buf[i + 1] = g; buf[i + 2] = b; buf[i + 3] = 255;
        continue;
      }
      const coverage = clamp(0.5 - sdf(gx, gy) / k, 0, 1);
      if (coverage <= 0) continue;
      buf[i] = tr; buf[i + 1] = tg; buf[i + 2] = tb;
      buf[i + 3] = Math.round(coverage * 255);
    }
  }
  return buf;
}

// ------------------------------------------------------------------ ICO container
function encodeIco(sizes) {
  const pngs = sizes.map((s) => encodePng(s, rasterise(s)));
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(sizes.length, 4);
  const dir = Buffer.alloc(16 * sizes.length);
  let offset = 6 + dir.length;
  sizes.forEach((s, i) => {
    const o = i * 16;
    dir[o] = s >= 256 ? 0 : s;
    dir[o + 1] = s >= 256 ? 0 : s;
    dir[o + 2] = 0; dir[o + 3] = 0;
    dir.writeUInt16LE(1, o + 4);        // planes
    dir.writeUInt16LE(32, o + 6);       // bpp
    dir.writeUInt32LE(pngs[i].length, o + 8);
    dir.writeUInt32LE(offset, o + 12);
    offset += pngs[i].length;
  });
  return Buffer.concat([header, dir, ...pngs]);
}

// ------------------------------------------------------------------ assertions
const ICO_SIZES = [16, 32, 48];
const PNGS = { 'icon.png': 512, 'apple-icon.png': 180 };

const ico = encodeIco(ICO_SIZES);

// decode the container back and prove every entry is our three colours, not a rasteriser's
// approximation of them
(() => {
  const count = ico.readUInt16LE(4);
  if (count !== ICO_SIZES.length) throw new Error(`ico has ${count} entries, expected ${ICO_SIZES.length}`);
  const want = new Set([TILE, GLYPH, ACCENT]);
  ICO_SIZES.forEach((size, i) => {
    const o = 6 + i * 16;
    const w = ico[o], h = ico[o + 1];
    if (w !== size || h !== size) throw new Error(`entry ${i} claims ${w}x${h}, expected ${size}`);
    const len = ico.readUInt32LE(o + 8), off = ico.readUInt32LE(o + 12);
    const body = ico.slice(off, off + len);
    if (!body.slice(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) {
      throw new Error(`entry ${i} is not a PNG`);
    }
    if (body.readUInt32BE(16) !== size || body.readUInt32BE(20) !== size) {
      throw new Error(`entry ${i} IHDR is not ${size}x${size}`);
    }
  });
  // and the pixels themselves: every fully opaque pixel must be one of the three colours.
  // The tile's rounded edge is allowed partial alpha (that is what keeps the corner curved);
  // nothing else may be blended.
  for (const size of ICO_SIZES) {
    const px = rasterise(size);
    const seen = new Set();
    for (let i = 0; i < size * size; i++) {
      if (px[i * 4 + 3] < 128) continue;
      const hex = '#' + [0, 1, 2].map((c) => px[i * 4 + c].toString(16).padStart(2, '0')).join('').toUpperCase();
      if (px[i * 4 + 3] === 255) {
        seen.add(hex);
        if (!want.has(hex)) throw new Error(`${size}px has an opaque ${hex}, outside the mark's three colours`);
      } else if (hex !== TILE) {
        throw new Error(`${size}px has a blended ${hex} that is not the tile edge`);
      }
    }
    if (!seen.has(TILE) || !seen.has(GLYPH) || !seen.has(ACCENT)) {
      throw new Error(`${size}px is missing one of the three mark colours: ${[...seen].join(' ')}`);
    }
  }
})();

